"""Write docs/schema/userdefaults-keys.md from Sourcery's key inventory.

Sourcery (templates/UserDefaultsSchema.stencil) lists every `static let *Key`
String constant in PhaseTraining/. This script adds two coverage columns:

  Wiped      MemoryStore.wipeAllUserData deletes keys by the `pt_` prefix.
  In backup  the key's literal appears in BackupManager.swift, which is how
             BackupManager.snapshot reads UserDefaults.

    uv run scripts/schema/userdefaults_registry.py build/sourcery/userdefaults-keys.tsv
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BACKUP = REPO / "PhaseTraining" / "Data" / "BackupManager.swift"
OUT = REPO / "docs" / "schema" / "userdefaults-keys.md"

# Keys whose data moved into user.db; the backup covers them through the DB.
MIGRATED_TO_USER_DB = {"pt_sessions": "sessions", "pt_custom_routines": "user_routines"}


def main() -> None:
    tsv = Path(sys.argv[1])
    backup_src = BACKUP.read_text()
    rows = []
    for line in tsv.read_text().splitlines():
        if not line.strip():
            continue
        owner, const, literal = line.split("\t")
        key = literal.strip().strip('"')
        wiped = key.startswith("pt_")
        if key in MIGRATED_TO_USER_DB:
            backup = f"via user.db `{MIGRATED_TO_USER_DB[key]}`"
        else:
            backup = "yes" if f'"{key}"' in backup_src else "no"
        rows.append((key, owner, const, wiped, backup))
    rows.sort()

    not_wiped = [r[0] for r in rows if not r[3]]
    not_backed = [r[0] for r in rows if r[4] == "no"]
    lines = [
        "# UserDefaults key registry",
        "",
        "Generated by `scripts/schema/gen_docs.sh` from Sourcery's scan of `PhaseTraining/`. "
        "Do not edit by hand.",
        "",
        f"{len(rows)} keys. {len(not_wiped)} {'survives' if len(not_wiped) == 1 else 'survive'} Erase All Data "
        f"(no `pt_` prefix). {len(not_backed)} are not in the backup envelope.",
        "",
        "| Key | Owner | Constant | Wiped | In backup |",
        "|---|---|---|---|---|",
    ]
    for key, owner, const, wiped, backup in rows:
        lines.append(f"| `{key}` | {owner} | `{const}` | {'yes' if wiped else '**no**'} | {backup} |")
    OUT.write_text("\n".join(lines) + "\n")

    print(f"{OUT.relative_to(REPO)}: {len(rows)} keys")
    if not_wiped:
        print("  not wiped:", ", ".join(not_wiped))
    if not_backed:
        print("  not in backup:", ", ".join(not_backed))


if __name__ == "__main__":
    main()
